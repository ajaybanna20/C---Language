/* write a c program input character and check character is q,w,e,r,t,y,u,i,o,p : upper line
otherwise :input is not matched */
#include <stdio.h>
int main () {
	char ch;
	printf("enter a character: ");
	scanf("%c",&ch);
	if (ch =='q') {
		printf("upper line");
	}
	else if (ch == 'w') {
		printf("upper line");
	}
	else if (ch == 'e') {
		printf("upper line");
	} 
	else if (ch == 'r') {
		printf("upper line");
	}
	else if (ch == 't') {
		printf("upper line");
	}
	else if (ch == 'y') {
		printf("upper line");
	}
	else if (ch == 'u') {
		printf("upper line");
	}
	else if (ch == 'i') {
		printf("upper line");
	}
	else if (ch == 'o') {
		printf("upper line");
	}
	else if (ch == 'p') {
		printf("upper line");
	}
	else {
		printf("input is not matched");
	}
return 0;
}
